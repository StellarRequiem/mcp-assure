"""The one deliberate way to change the mcp-defense-bench baseline.

    python tests/mcp_defense/update_baseline.py           # show what would change, write nothing
    python tests/mcp_defense/update_baseline.py --write   # rewrite baseline.json and RESULTS.md

Run it after a change that is meant to alter results (or after bumping a pin in
requirements.txt and harness.PINS together), review the diff, and commit both files. CI and the
test suite only ever read the baseline.
"""

from __future__ import annotations

import json
import sys
from collections import Counter
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

import harness


def results_md(r: dict) -> str:
    p, dev, ben = r["pins"], r["dev"], r["benign"]
    ds, bs = dev["summary"], ben["summary"]
    ci = bs["deniedRate95ci"]
    out = [
        "# mcp-defense-bench results for mcp-assure",
        "",
        "Generated by `update_baseline.py --write` from the same run as `baseline.json`; do not",
        "edit by hand. Config: `build_assure_middleware` with the operator pack in",
        '`operator_pack.py`. Read these as "this pack on this corpus", not as a rating.',
        "",
        "## Pins",
        "",
        f"- Scorer: mcp-defense-bench {p['mcp-defense-bench']} ([source]({p['scorerSource']}))",
        f"- Corpus: bench commit `{p['benchCommit']}`, MANIFEST.json sha256 `{p['manifestSha256']}`",
        f"- FastMCP {p['fastmcp']}, MCP SDK {p['mcp']}",
        "",
        "## Summary",
        "",
        "| Corpus | Fixtures | Scored | Skipped | Errors | Result |",
        "|---|---|---|---|---|---|",
        (
            f"| dev (matched cases) | {ds['cases']} | {ds['scored']} | {ds['skipped']} "
            f"| {ds['errors']} | {ds['overall']}; enforce {ds['enforce']}, detect {ds['detect']}, "
            f"none {ds['none']}; matched controls denied {ds['matchedFalsePositives']} |"
        ),
        (
            f"| benign | {bs['items']} | {bs['scored']} | {bs['skipped']} | {bs['errors']} "
            f"| {bs['denied']} denied (Wilson 95% {ci['lo']}–{ci['hi']}) |"
        ),
        "",
        "A matched dev case scores **enforce** when the attack fixture is blocked and its benign",
        "control is not, **detect** for a warning only, **none** otherwise. mcp-assure gates tool",
        "names and argument *names*; attacks carried in argument values, results or tool",
        "definitions are outside that layer, so most scored cases are expected to be `none`.",
        "",
        "## Dev: scored cases",
        "",
        "| Case | Fixture type | Level | Control denied |",
        "|---|---|---|---|",
    ]
    for fid, c in sorted(dev["cases"].items()):
        out.append(
            f"| `{fid}` | {c['type']} | {c['level']} | {'yes' if c['falsePositive'] else 'no'} |"
        )
    out += ["", "## Skipped fixtures", ""]
    out += [
        "The scorer's FastMCP adapter replays only `tools/list` and `tools/call` traffic. Fixture",
        "types it cannot express stay `unknown` (never counted as misses), per the bench's",
        "integrity rule.",
        "",
        f"Dev: {ds['skipped']} of {ds['cases']} cases skipped, by fixture type: "
        + ", ".join(f"{t} {n}" for t, n in sorted(Counter(dev["skipped"].values()).items()))
        + ".",
        "",
        f"Benign: {bs['scored']} of {bs['items']} items scored; these {bs['skipped']} are skipped:",
        "",
        "| Item | Fixture type | Why it can't be replayed through a FastMCP middleware |",
        "|---|---|---|",
    ]
    for fid, t in sorted(ben["skipped"].items()):
        out.append(
            f"| `{fid}` | {t} | {harness.SKIP_REASONS.get(t, 'not tools/list or tools/call')} |"
        )
    kinds = Counter(i["kind"] for i in ben["items"].values())
    denied = sorted(fid for fid, i in ben["items"].items() if i["denied"])
    out += [
        "",
        "## Benign: scored items",
        "",
        "By kind: " + ", ".join(f"{k} {n}" for k, n in sorted(kinds.items())) + ".",
        "",
        "Denied: " + (", ".join(f"`{d}`" for d in denied) if denied else "none") + ".",
        "",
        "Every item's verdict is in `baseline.json` (`benign.items`).",
        "",
    ]
    return "\n".join(out)


def main() -> int:
    problems = harness.pin_problems()
    if problems:
        print("installed versions differ from harness.PINS:\n  " + "\n  ".join(problems))
        return 2
    cur = harness.run()
    if harness.BASELINE.exists():
        bad, good = harness.compare(json.loads(harness.BASELINE.read_text("utf8")), cur)
        for line in bad:
            print(f"- {line}")
        for line in good:
            print(f"+ {line}")
        if not bad and not good:
            print("no per-fixture changes vs baseline")
    if "--write" not in sys.argv[1:]:
        print("dry run; pass --write to rewrite baseline.json and RESULTS.md")
        return 0
    harness.BASELINE.write_text(json.dumps(cur, indent=2, sort_keys=True) + "\n", "utf8")
    harness.RESULTS.write_text(results_md(cur), "utf8")
    print(f"wrote {harness.BASELINE.name} and {harness.RESULTS.name}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
